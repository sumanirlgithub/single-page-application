package com.neo.payments.hub.dao.payment;

import com.neo.payments.hub.model.payment.PaymentDocument;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.RowMapper;
import org.springframework.stereotype.Repository;

import java.sql.Timestamp;
import java.time.Instant;
import java.util.List;
import java.util.Optional;

@Repository
public class PaymentDocumentRepository {

    private final JdbcTemplate jdbcTemplate;

    public PaymentDocumentRepository(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
    }

    private static final RowMapper<PaymentDocument> PAYMENT_DOCUMENT_ROW_MAPPER =
            (rs, rowNum) -> {

                Timestamp createdAtTimestamp =
                        rs.getTimestamp("CREATED_AT");

                Instant createdAt = createdAtTimestamp != null
                        ? createdAtTimestamp.toInstant()
                        : null;

                return new PaymentDocument(
                        rs.getLong("DOCUMENT_ID"),
                        rs.getString("PAYMENT_ID"),
                        rs.getString("DOCUMENT_TYPE"),
                        rs.getString("DOCUMENT_CONTENT"),
                        rs.getString("DOCUMENT_STATUS"),
                        createdAt
                );
            };

    /**
     * Save a payment document.
     *
     * DOCUMENT_ID and CREATED_AT are generated by MySQL.
     */
    public PaymentDocument save(PaymentDocument document) {

        String sql = """
                INSERT INTO PAYMENT_DOCUMENT (
                    PAYMENT_ID,
                    DOCUMENT_TYPE,
                    DOCUMENT_CONTENT,
                    DOCUMENT_STATUS,
                    CREATED_AT
                )
                VALUES (?, ?, ?, ?, ?)
                """;

        Instant createdAt = document.createdAt() != null
                ? document.createdAt()
                : Instant.now();

        Timestamp timestamp = Timestamp.from(createdAt);

        jdbcTemplate.update(
                sql,
                document.paymentId(),
                document.documentType(),
                document.documentContent(),
                document.documentStatus(),
                timestamp
        );

        Long documentId = jdbcTemplate.queryForObject(
                "SELECT LAST_INSERT_ID()",
                Long.class
        );

        return new PaymentDocument(
                documentId,
                document.paymentId(),
                document.documentType(),
                document.documentContent(),
                document.documentStatus(),
                createdAt
        );
    }

    /**
     * Find document by its primary key.
     */
    public Optional<PaymentDocument> findById(Long documentId) {

        String sql = """
                SELECT
                    DOCUMENT_ID,
                    PAYMENT_ID,
                    DOCUMENT_TYPE,
                    DOCUMENT_CONTENT,
                    DOCUMENT_STATUS,
                    CREATED_AT
                FROM PAYMENT_DOCUMENT
                WHERE DOCUMENT_ID = ?
                """;

        List<PaymentDocument> documents = jdbcTemplate.query(
                sql,
                PAYMENT_DOCUMENT_ROW_MAPPER,
                documentId
        );

        return documents.stream().findFirst();
    }

    /**
     * Find all documents belonging to a payment.
     */
    public List<PaymentDocument> findByPaymentId(String paymentId) {

        String sql = """
                SELECT
                    DOCUMENT_ID,
                    PAYMENT_ID,
                    DOCUMENT_TYPE,
                    DOCUMENT_CONTENT,
                    DOCUMENT_STATUS,
                    CREATED_AT
                FROM PAYMENT_DOCUMENT
                WHERE PAYMENT_ID = ?
                ORDER BY CREATED_AT DESC
                """;

        return jdbcTemplate.query(
                sql,
                PAYMENT_DOCUMENT_ROW_MAPPER,
                paymentId
        );
    }

    /**
     * Find a document by payment ID and document type.
     */
    public Optional<PaymentDocument> findByPaymentIdAndDocumentType(
            String paymentId,
            String documentType) {

        String sql = """
                SELECT
                    DOCUMENT_ID,
                    PAYMENT_ID,
                    DOCUMENT_TYPE,
                    DOCUMENT_CONTENT,
                    DOCUMENT_STATUS,
                    CREATED_AT
                FROM PAYMENT_DOCUMENT
                WHERE PAYMENT_ID = ?
                  AND DOCUMENT_TYPE = ?
                ORDER BY CREATED_AT DESC
                LIMIT 1
                """;

        List<PaymentDocument> documents = jdbcTemplate.query(
                sql,
                PAYMENT_DOCUMENT_ROW_MAPPER,
                paymentId,
                documentType
        );

        return documents.stream().findFirst();
    }

    /**
     * Update document status.
     */
    public int updateStatus(
            Long documentId,
            String documentStatus) {

        String sql = """
                UPDATE PAYMENT_DOCUMENT
                SET DOCUMENT_STATUS = ?
                WHERE DOCUMENT_ID = ?
                """;

        return jdbcTemplate.update(
                sql,
                documentStatus,
                documentId
        );
    }

    /**
     * Check whether a document exists for a payment and type.
     */
    public boolean existsByPaymentIdAndDocumentType(
            String paymentId,
            String documentType) {

        String sql = """
                SELECT COUNT(*)
                FROM PAYMENT_DOCUMENT
                WHERE PAYMENT_ID = ?
                  AND DOCUMENT_TYPE = ?
                """;

        Integer count = jdbcTemplate.queryForObject(
                sql,
                Integer.class,
                paymentId,
                documentType
        );

        return count != null && count > 0;
    }
}